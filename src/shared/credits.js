// Asset credits: origin, author, licence and status for every image, written as Markdown and CSV.
// Used by the library generator and by the app (library folder and each project folder).
const KIND_ORDER = ['tilesets', 'characters', 'monsters', 'battlebacks', 'pictures', 'decorations', 'music', 'sounds', 'movies', 'other'];
const KIND_NAME = { tilesets: 'Tilesets', characters: 'Characters and event objects', monsters: 'Monsters', battlebacks: 'Battle backgrounds', pictures: 'Pictures', decorations: 'Decorations (furniture)', music: 'Music and jingles', sounds: 'Sound effects', movies: 'Movies (cut scenes)', other: 'Other' };
const STATUSES = ['Placeholder', 'Custom', 'Third-party'];

const DEFAULT_ORIGIN = 'Original pixel art made for Pocket-Game-Maker (generated by its built-in asset generator, 2026). Colours from the Endesga 32 palette.';
const DEFAULT = { author: 'Pocket-Designs', licence: 'CC0 1.0 (public domain)', status: 'Placeholder', origin: DEFAULT_ORIGIN };

function kindOf(file) { const k = String(file).split('/')[0]; return KIND_ORDER.includes(k) ? k : 'other'; }
function rows(entries) {
  return Object.keys(entries).map(file => Object.assign({ file, kind: kindOf(file) }, entries[file]))
    .sort((a, b) => KIND_ORDER.indexOf(a.kind) - KIND_ORDER.indexOf(b.kind) || a.file.localeCompare(b.file));
}
const cell = v => String(v == null || v === '' ? '—' : v).replace(/\|/g, '/').replace(/\r?\n/g, ' ');

function toMarkdown(title, entries, intro) {
  const r = rows(entries);
  const count = s => r.filter(x => (x.status || '') === s).length;
  let out = '# ' + title + '\n\n' + (intro ? intro + '\n\n' : '');
  out += 'Total: ' + r.length + ' assets (' + STATUSES.map(s => count(s) + ' ' + s.toLowerCase()).join(', ') + ').\n';
  for (const k of KIND_ORDER) {
    const list = r.filter(x => x.kind === k);
    if (!list.length) continue;
    out += '\n## ' + KIND_NAME[k] + '\n\n| File | Name | Status | Origin | Author | Licence |\n| --- | --- | --- | --- | --- | --- |\n';
    for (const x of list) out += '| ' + [x.file, x.name, x.status, x.origin, x.author, x.licence].map(cell).join(' | ') + ' |\n';
  }
  return out;
}
function toCSV(entries) {
  const q = v => '"' + String(v == null ? '' : v).replace(/"/g, '""') + '"';
  return ['file,kind,name,status,origin,author,licence'].concat(rows(entries).map(x => [x.file, x.kind, x.name, x.status, x.origin, x.author, x.licence].map(q).join(','))).join('\r\n') + '\r\n';
}

// Flatten library.json (items keyed per tileset/character/monster/background) into one entry per file.
function fromLibraryMeta(meta) {
  const out = {};
  for (const kind of ['tilesets', 'characters', 'monsters', 'battlebacks', 'pictures', 'decorations', 'music', 'sounds', 'movies']) {
    for (const [key, m] of Object.entries(meta[kind] || {})) {
      const e = { name: m.name || key, origin: m.origin || '', author: m.author || '', licence: m.licence || '', status: m.status || '' };
      const files = kind === 'monsters' ? [key + '_front.png', key + '_back.png'] : [key];
      files.forEach(f => { out[f] = Object.assign({}, e, kind === 'monsters' ? { name: e.name + (f.endsWith('_front.png') ? ' (front)' : ' (back)') } : {}); });
      if (kind === 'tilesets' && m.mapping) out[m.mapping] = Object.assign({}, e, { name: e.name + ' tile mapping', origin: e.status === 'Placeholder' ? 'Tile names and settings written for Pocket-Game-Maker.' : e.origin });
    }
  }
  return out;
}

module.exports = { fromLibraryMeta, DEFAULT, DEFAULT_ORIGIN, STATUSES, KIND_ORDER, KIND_NAME, rows, toMarkdown, toCSV, kindOf };
